SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS artisti (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  slug VARCHAR(90) NULL,
  livello ENUM('punta','superficie','profondo','abisso') NOT NULL DEFAULT 'superficie',
  stile VARCHAR(120) NOT NULL DEFAULT '',
  bio TEXT NULL,
  progetto VARCHAR(120) NULL,
  brano VARCHAR(120) NULL,
  plays INT NOT NULL DEFAULT 0,
  monthly_listeners INT NOT NULL DEFAULT 0,
  link VARCHAR(255) NULL,
  link_soundcloud VARCHAR(255) NULL,
  link_youtube VARCHAR(255) NULL,
  link_instagram VARCHAR(255) NULL,
  link_spotify VARCHAR(255) NULL,
  avatar_url VARCHAR(255) NULL,
  note TEXT NULL,
  is_goat TINYINT(1) NOT NULL DEFAULT 0,
  creato_il TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4 ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS utenti (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  bio TEXT NULL,
  badge VARCHAR(60) NOT NULL DEFAULT 'SoundCloud Lurker',
  avatar_color VARCHAR(20) NOT NULL DEFAULT '#a3e635',
  ruolo ENUM('user','mod','admin') NOT NULL DEFAULT 'user',
  creato_il TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4 ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tracce (
  id INT AUTO_INCREMENT PRIMARY KEY,
  artista_id INT NOT NULL,
  titolo VARCHAR(150) NOT NULL,
  progetto VARCHAR(150) NULL,
  anno INT NULL DEFAULT 2024,
  plays INT NOT NULL DEFAULT 0,
  produttore VARCHAR(150) NULL,
  link_audio VARCHAR(255) NULL,
  is_hit TINYINT(1) NOT NULL DEFAULT 0,
  creato_il TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (artista_id) REFERENCES artisti(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4 ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS post (
  id INT AUTO_INCREMENT PRIMARY KEY,
  utente_id INT NOT NULL,
  artista_id INT NULL,
  titolo VARCHAR(255) NOT NULL,
  flair VARCHAR(50) NOT NULL DEFAULT 'DISCUSSIONE',
  contenuto TEXT NOT NULL,
  link_esterno VARCHAR(255) NULL,
  upvotes INT NOT NULL DEFAULT 1,
  creato_il TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (utente_id) REFERENCES utenti(id) ON DELETE CASCADE,
  FOREIGN KEY (artista_id) REFERENCES artisti(id) ON DELETE SET NULL
) CHARACTER SET utf8mb4 ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS commenti (
  id INT AUTO_INCREMENT PRIMARY KEY,
  post_id INT NOT NULL,
  utente_id INT NOT NULL,
  testo TEXT NOT NULL,
  upvotes INT NOT NULL DEFAULT 0,
  creato_il TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE,
  FOREIGN KEY (utente_id) REFERENCES utenti(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4 ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS post_upvotes (
  post_id INT NOT NULL,
  utente_id INT NOT NULL,
  PRIMARY KEY (post_id, utente_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS comment_upvotes (
  comment_id INT NOT NULL,
  utente_id INT NOT NULL,
  PRIMARY KEY (comment_id, utente_id)
) ENGINE=InnoDB;
